"""OFFLINE ONLY: verify an operator-key signature over an exact key-rotation proposal.

This is a non-promoting inspection prototype. There is no operator login,
consent UI, signing service, key provisioning, key storage, durable nonce
tracking, systemd access, production key activation or deployment. Pinned
operator and verifier public keys and expected device/challenge come ONLY
from an independently trusted caller, NEVER from the signed payload.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import re

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from core.selfdev_verifier_key_rotation import (
    TrustedVerifierKey, _validate_anchor, inspect_rotation, key_fingerprint,
)

DOMAIN = b"MyAI/independent-operator/offline-key-rotation-review/v1\0"
PURPOSE = "review-verifier-key-change-only"
ISSUER = "myai-independent-operator-approval-v1"
AUDIENCE = "myai-updater-source-inspection-only"
MAX_ENVELOPE = 3072
MAX_DURATION = 300
DEVICE = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
HEX32 = re.compile(r"[0-9a-f]{32}\Z")
HEX64 = re.compile(r"[0-9a-f]{64}\Z")
HEX128 = re.compile(r"[0-9a-f]{128}\Z")
FIELDS = frozenset({
    "version", "issuer", "purpose", "audience", "device_id",
    "rotation_sha256", "old_key_sha256", "new_key_sha256",
    "old_epoch", "new_epoch", "operator_challenge",
    "not_before_unix", "expires_unix",
})


@dataclass(frozen=True)
class OperatorReview:
    device_id: str
    rotation_sha256: str
    old_epoch: int
    proposed_epoch: int
    old_key_sha256: str
    proposed_key_sha256: str
    pinned_operator_signature_verified: bool = True
    verifier_dual_signature_verified: bool = True
    independently_authenticated_human_intent_verified: bool = False
    durable_operator_nonce_consumption_verified: bool = False
    independent_checkpoint_advanced: bool = False
    verifier_signing_key_activated: bool = False
    authorizes_mutation: bool = False
    production_deployment_authorized: bool = False


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate operator approval JSON field")
        result[key] = value
    return result


def _bad_constant(_):
    raise ValueError("Nonfinite operator approval number")


def _hex(value, pattern, description):
    if type(value) is not str or pattern.fullmatch(value) is None:
        raise ValueError("Invalid " + description)
    return value


def canonical_operator_review(statement):
    """Canonical, domain-separated Ed25519 signing bytes (no optional fields)."""
    if type(statement) is not dict or set(statement) != FIELDS:
        raise ValueError("Unexpected operator review fields")
    if type(statement["version"]) is not int or statement["version"] != 1:
        raise ValueError("Unsupported operator review version")
    if (statement["issuer"] != ISSUER or statement["purpose"] != PURPOSE
            or statement["audience"] != AUDIENCE):
        raise ValueError("Incorrect operator review domain")
    device = statement["device_id"]
    if type(device) is not str or DEVICE.fullmatch(device) is None:
        raise ValueError("Malformed device identity")
    for key in ("rotation_sha256", "old_key_sha256", "new_key_sha256"):
        _hex(statement[key], HEX64, key)
    _hex(statement["operator_challenge"], HEX32, "operator challenge")
    old, new = statement["old_epoch"], statement["new_epoch"]
    if (type(old) is not int or type(new) is not int
            or old < 1 or new != old + 1 or new >= 2**31):
        raise ValueError("Review key epochs must increment exactly once")
    before, expiry = statement["not_before_unix"], statement["expires_unix"]
    if (type(before) is not int or type(expiry) is not int
            or before < 0 or not before < expiry
            or expiry - before > MAX_DURATION):
        raise ValueError("Unsafe operator review lifetime")
    if statement["old_key_sha256"] == statement["new_key_sha256"]:
        raise ValueError("Operator review does not change key")
    return DOMAIN + json.dumps(
        statement, sort_keys=True, separators=(",", ":"),
        ensure_ascii=True, allow_nan=False,
    ).encode("ascii")


def inspect_operator_review(
    operator_envelope, rotation_envelope, *,
    trusted_operator_public_key, trusted_verifier_anchor,
    expected_device_id, expected_operator_challenge, now_unix,
):
    """Require separate operator key AND verifier's old/new key signatures.

    The returned result never calls an updater, writes a checkpoint, changes
    a trusted anchor, or establishes an authenticated human approval channel.
    Even both signatures could be generated by compromised/off-device keys.
    """
    if type(trusted_verifier_anchor) is not TrustedVerifierKey:
        raise ValueError("Missing pinned verifier key")
    old_fp = _validate_anchor(trusted_verifier_anchor)
    operator_fp = key_fingerprint(trusted_operator_public_key)
    if operator_fp == old_fp:
        raise ValueError("Operator and verifier key roles must be separate")
    if (type(expected_device_id) is not str
            or DEVICE.fullmatch(expected_device_id) is None):
        raise ValueError("Missing trusted device identity")
    _hex(expected_operator_challenge, HEX32, "trusted operator challenge")
    if type(now_unix) is not int or now_unix < 0:
        raise ValueError("Invalid trusted clock")
    if (type(operator_envelope) is not bytes or not 0 < len(operator_envelope)
            <= MAX_ENVELOPE):
        raise ValueError("Oversized or invalid operator review envelope")
    try:
        wrapped = json.loads(
            operator_envelope.decode("utf-8"),
            object_pairs_hook=_unique_object,
            parse_constant=_bad_constant,
        )
    except (UnicodeError, ValueError, RecursionError) as exc:
        raise ValueError("Malformed operator review envelope") from exc
    if type(wrapped) is not dict or set(wrapped) != {"statement", "signature"}:
        raise ValueError("Untrusted operator approval envelope keys")
    statement = wrapped["statement"]
    signing_bytes = canonical_operator_review(statement)
    signature = _hex(wrapped["signature"], HEX128, "operator signature")
    if (statement["device_id"] != expected_device_id
            or statement["operator_challenge"] != expected_operator_challenge
            or statement["old_epoch"] != trusted_verifier_anchor.epoch
            or statement["old_key_sha256"] != old_fp):
        raise ValueError("Operator review does not match trusted device/context")
    if not statement["not_before_unix"] <= now_unix < statement["expires_unix"]:
        raise ValueError("Operator review not yet valid or expired")
    try:
        Ed25519PublicKey.from_public_bytes(trusted_operator_public_key).verify(
            bytes.fromhex(signature), signing_bytes,
        )
    except (InvalidSignature, ValueError) as exc:
        raise ValueError("Invalid independently pinned operator key signature") from exc
    # The operator-signed exact hash is now the only digest admitted to the
    # pre-existing two-verifier-signature rotation inspection. Do not permit
    # untrusted callers to inject an independent-approved-digest argument.
    inspection = inspect_rotation(
        rotation_envelope,
        pinned_key=trusted_verifier_anchor,
        expected_operator_nonce=expected_operator_challenge,
        independently_approved_payload_sha256=statement["rotation_sha256"],
        now_unix=now_unix,
    )
    if (inspection.old_key_sha256 != statement["old_key_sha256"]
            or inspection.proposed_key_sha256 != statement["new_key_sha256"]
            or inspection.old_epoch != statement["old_epoch"]
            or inspection.proposed_epoch != statement["new_epoch"]):
        raise ValueError("Operator review differs from signed verifier rotation")
    return OperatorReview(
        device_id=expected_device_id,
        rotation_sha256=statement["rotation_sha256"],
        old_epoch=inspection.old_epoch,
        proposed_epoch=inspection.proposed_epoch,
        old_key_sha256=inspection.old_key_sha256,
        proposed_key_sha256=inspection.proposed_key_sha256,
    )
